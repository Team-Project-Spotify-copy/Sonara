/** Glyphs whose body is a solid shape rather than an outline. */
const FILLED = new Set(["prev", "next", "play", "pause"]);

export default function Glyph({ name, filled = false, size }) {
  const box = BOX[name];
  const paths = STROKED[name];
  if (!box || !paths) return null;

  const [viewBox, defaultWidth, defaultHeight] = box;
  const scale = size ? size / Math.max(defaultWidth, defaultHeight) : 1;

  const solid = FILLED.has(name) || (name === "star" && filled);

  return (
    <svg
      className="glyph"
      viewBox={viewBox}
      width={Math.round(defaultWidth * scale)}
      height={Math.round(defaultHeight * scale)}
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {paths.map((d) => (
        <path key={d} d={d} fill={solid ? "currentColor" : "none"} />
      ))}
    </svg>
  );
}
